const mirror = (rows: string[]) => rows.map((r) => [...r].reverse().join(''));
const flip = (rows: string[]) => [...rows].reverse();

const ALL = { ...BITMAPS, redo: mirror(BITMAPS.undo), down: flip(BITMAPS.up), prev: mirror(BITMAPS.next) };

export type IconName = keyof typeof ALL;

/** One SVG path per icon: a horizontal run of pixels becomes one rectangle. */
function toPath(rows: string[]): string {
  let d = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] !== '#') continue;
      let end = x;
      while (row[end + 1] === '#') end++;
      d += `M${x} ${y}h${end - x + 1}v1h-${end - x + 1}z`;
      x = end;
    }
  });
  return d;
}

const PATHS = Object.fromEntries(Object.entries(ALL).map(([k, rows]) => [k, toPath(rows)])) as Record<IconName, string>;

export function Icon({ name, size = 24 }: { name: IconName; size?: number }) {
  return (
    <svg width={size} height={size} viewBox="0 0 12 12" shapeRendering="crispEdges" aria-hidden="true" focusable="false">
      <path d={PATHS[name]} fill="currentColor" />
    </svg>
  );
}

/** The Pontilha mark: a 3×3 stitch of dots with the centre one in saffron. */
export function Mark({ size = 20 }: { size?: number }) {
  const dots = [0, 1, 2].flatMap((row) => [0, 1, 2].map((col) => ({ row, col })));
  return (
    <svg width={size} height={size} viewBox="0 0 10 10" shapeRendering="crispEdges" aria-hidden="true">
      {dots.map(({ row, col }) => (
        <rect
          key={`${row}${col}`}
          x={1 + col * 3}
          y={1 + row * 3}
          width={2}
          height={2}
          fill={row === 1 && col === 1 ? 'var(--saffron)' : 'currentColor'}
        />
      ))}
    </svg>
  );
}
